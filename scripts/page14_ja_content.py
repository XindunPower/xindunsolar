def assert_no_translate_error(text: str) -> None:
    if re.search(r"Error\s*500|Server Error", text, re.I):
        raise RuntimeError("Google Translate Error 500/Server Error found in Japanese content")


def assert_article(art: dict) -> None:
    for key in ("title_ja", "seo_title_ja", "description_ja", "focuskw_ja", "body_html"):
        assert_no_translate_error(art[key])
    if "<a " in art["body_html"].lower() or "</a>" in art["body_html"].lower():
        raise RuntimeError(f"hyperlink in body: {art['title_en']}")
    if re.search(r"\{img0\}", art["body_html"]):
        raise RuntimeError(f"featured image must not be placed in the body: {art['title_en']}")
    if re.search(r"font-size:\s*18pt", art["body_html"], re.I):
        raise RuntimeError(f"duplicate 18pt title in body: {art['title_en']}")


